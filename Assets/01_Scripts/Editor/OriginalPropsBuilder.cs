namespace OperationHeist.Editor
{
    public static class OriginalPropsBuilder
    {
        private const string ModelDirectory = "Assets/04_Models/Codex";
        private const string PrefabDirectory = "Assets/02_Prefabs/Props";
        private struct Part
        {
            public Vector3 center, size;
            public int material;
            public float rotation;
            public Part(Vector3 center, Vector3 size, int material = 0, float rotation = 0)
            { this.center = center; this.size = size; this.material = material; this.rotation = rotation; }
        }

        [MenuItem("Operation Heist/Crear kit original e integrar")]
        public static void BuildAndValidate()
        {
            Directory.CreateDirectory(ModelDirectory);
            Directory.CreateDirectory(PrefabDirectory);
            FpsPrototypeBuilder.Build();
            var materials = new[] {
                FpsPrototypeBuilder.OriginalMaterial("OH_PropSteel", new Color(0.19f, 0.32f, 0.34f)),
                FpsPrototypeBuilder.OriginalMaterial("OH_PropDark", new Color(0.08f, 0.1f, 0.12f)),
                FpsPrototypeBuilder.OriginalMaterial("OH_PropBrass", new Color(0.76f, 0.48f, 0.15f))
            };
            Create("TransportCrate", Crate(), materials);
            Create("StorageShelf", Shelf(), materials);
            Create("ServiceCounter", Counter(), materials);
            Create("CompactSafe", Safe(), materials);
            AssetDatabase.SaveAssets();

            Scene previous = SceneManager.GetActiveScene();
            Scene scene = EditorSceneManager.OpenScene("Assets/00_Scenes/FPSPrototype.unity",
                Application.isBatchMode ? OpenSceneMode.Single : OpenSceneMode.Additive);
            try
            {
                SceneManager.SetActiveScene(scene);
                Place("TransportCrate", new Vector3(-4, 0, 1), scene);
                Place("StorageShelf", new Vector3(-7, 0, 4), scene);
                Place("ServiceCounter", new Vector3(4, 0, 4), scene);
                Place("CompactSafe", new Vector3(7, 0, 7), scene);
                if (!EditorSceneManager.SaveScene(scene)) throw new IOException("No se pudo guardar FPSPrototype.");
                var report = new List<string> { "Original models generated by project code with Codex assistance; no downloaded meshes or textures." };
                foreach (string name in new[] { "TransportCrate", "StorageShelf", "ServiceCounter", "CompactSafe" })
                {
                    var prefab = AssetDatabase.LoadAssetAtPath<GameObject>($"{PrefabDirectory}/OH_{name}.prefab");
                    if (prefab == null || prefab.GetComponent<BoxCollider>() == null) throw new Exception("Prefab inválido: " + name);
                    var mesh = prefab.GetComponent<MeshFilter>().sharedMesh;
                    if (mesh == null || mesh.vertexCount == 0 || mesh.bounds.min.y < -0.001f) throw new Exception("Mesh inválido: " + name);
                    foreach (var vertex in mesh.vertices)
                        if (float.IsNaN(vertex.x) || float.IsNaN(vertex.y) || float.IsNaN(vertex.z)) throw new Exception("Vértice inválido");
                    foreach (var material in prefab.GetComponent<MeshRenderer>().sharedMaterials)
                        if (material == null || material.GetTexture("_BaseMap") != null) throw new Exception("Material no permitido");
                    report.Add($"{name}: {mesh.vertexCount} vertices, {mesh.triangles.Length / 3} triangles, bounds {mesh.bounds.size}, collider OK");
                }
                Directory.CreateDirectory("Docs/QA");
                File.WriteAllLines("Docs/QA/OriginalModels-validation.txt", report);
                Debug.Log("ORIGINAL_MODELS_VALIDATED: 4 modelos, materiales propios, prefabs y escena integrados.");
            }
            finally
            {
                if (!Application.isBatchMode && previous.IsValid())
                { SceneManager.SetActiveScene(previous); EditorSceneManager.CloseScene(scene, true); }
            }
        }

        private static void Create(string name, List<Part> parts, Material[] materials)
        {
            var baseMesh = FpsPrototypeBuilder.OriginalCuboid();
            var vertices = new List<Vector3>();
            var triangles = new[] { new List<int>(), new List<int>(), new List<int>() };
            foreach (var part in parts)
            {
                int offset = vertices.Count;
                var matrix = Matrix4x4.TRS(part.center, Quaternion.Euler(0, 0, part.rotation), part.size);
                foreach (var vertex in baseMesh.vertices) vertices.Add(matrix.MultiplyPoint3x4(vertex));
                foreach (int index in baseMesh.triangles) triangles[part.material].Add(offset + index);
            }
            string path = $"{ModelDirectory}/OH_{name}.asset";
            var mesh = AssetDatabase.LoadAssetAtPath<Mesh>(path);
            bool isNew = mesh == null;
            if (isNew) mesh = new Mesh(); else mesh.Clear();
            mesh.name = "OH_" + name;
            mesh.SetVertices(vertices); mesh.subMeshCount = 3;
            for (int i = 0; i < 3; i++) mesh.SetTriangles(triangles[i], i);
            mesh.RecalculateNormals(); mesh.RecalculateBounds();
            if (isNew) AssetDatabase.CreateAsset(mesh, path); else EditorUtility.SetDirty(mesh);
            var root = new GameObject("OH_" + name, typeof(MeshFilter), typeof(MeshRenderer), typeof(BoxCollider));
            try
            {
                root.GetComponent<MeshFilter>().sharedMesh = mesh;
                root.GetComponent<MeshRenderer>().sharedMaterials = materials;
                var collider = root.GetComponent<BoxCollider>();
                collider.center = mesh.bounds.center; collider.size = mesh.bounds.size;
                string label = name == "TransportCrate" ? "caja de transporte" : name == "StorageShelf" ? "estantería" : name == "ServiceCounter" ? "mostrador" : "caja fuerte";
                root.AddComponent<PrototypeInteractable>().Configure(label);
                PrefabUtility.SaveAsPrefabAsset(root, $"{PrefabDirectory}/OH_{name}.prefab");
            }
            finally { UnityEngine.Object.DestroyImmediate(root); }
        }

        private static void Place(string name, Vector3 position, Scene scene)
        {
            var prefab = AssetDatabase.LoadAssetAtPath<GameObject>($"{PrefabDirectory}/OH_{name}.prefab");
            var instance = (GameObject)PrefabUtility.InstantiatePrefab(prefab, scene);
            instance.transform.position = position;
        }

        private static List<Part> Crate()
        {
            var p = new List<Part> { new Part(new Vector3(0,.3f,0),new Vector3(.8f,.6f,.55f)), new Part(new Vector3(0,.57f,0),new Vector3(.84f,.06f,.59f),1) };
            foreach (float x in new[] { -.29f, .29f }) p.Add(new Part(new Vector3(x,.31f,0),new Vector3(.07f,.62f,.57f),2));
            p.Add(new Part(new Vector3(0,.4f,-.29f),new Vector3(.2f,.06f,.04f),1));
            p.Add(new Part(new Vector3(0,.53f,-.3f),new Vector3(.07f,.1f,.04f),2));
            return p;
        }
        private static List<Part> Shelf()
        {
            var p = new List<Part>();
            foreach (float x in new[] { -.75f, .75f }) foreach (float z in new[] { -.22f, .22f })
                p.Add(new Part(new Vector3(x,1,z),new Vector3(.07f,2,.07f),1));
            foreach (float y in new[] { .12f,.72f,1.32f,1.92f })
                p.Add(new Part(new Vector3(0,y,0),new Vector3(1.6f,.06f,.52f)));
            p.Add(new Part(new Vector3(0,1.1f,.23f),new Vector3(.045f,1.9f,.035f),2,35));
            return p;
        }
        private static List<Part> Counter()
        {
            return new List<Part> {
                new Part(new Vector3(0,.48f,0),new Vector3(2.25f,.96f,.68f)),
                new Part(new Vector3(0,1.0f,0),new Vector3(2.4f,.1f,.82f),1),
                new Part(new Vector3(0,.08f,-.36f),new Vector3(2.27f,.16f,.05f),1),
                new Part(new Vector3(0,.76f,-.36f),new Vector3(2.27f,.05f,.05f),2),
                new Part(new Vector3(-.5f,.46f,-.36f),new Vector3(.04f,.5f,.04f),1),
                new Part(new Vector3(.5f,.46f,-.36f),new Vector3(.04f,.5f,.04f),1)
            };
        }
        private static List<Part> Safe()
        {
            var p = new List<Part> {
                new Part(new Vector3(0,.65f,0),new Vector3(.9f,1.3f,.75f),1),
                new Part(new Vector3(0,.68f,-.4f),new Vector3(.78f,1.12f,.1f)),
                new Part(new Vector3(.23f,.79f,-.47f),new Vector3(.18f,.22f,.04f),1),
                new Part(new Vector3(-.16f,.58f,-.49f),new Vector3(.07f,.07f,.1f),2)
            };
            for (int i=0;i<3;i++) p.Add(new Part(new Vector3(-.16f,.58f,-.55f),new Vector3(.33f,.035f,.04f),2,i*60));
            foreach(float y in new[] { .28f, 1.03f }) p.Add(new Part(new Vector3(-.4f,y,-.43f),new Vector3(.07f,.18f,.08f),2));
            return p;
        }
    }
